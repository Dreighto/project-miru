EMIT_DECISION_PATH = REPO_ROOT / "tools" / "emit_decision.py"


class EmitDecisionCLITests(unittest.TestCase):
    """Exercise the CLI as a real subprocess. Uses MIRU_DECISIONS_LOG_PATH for hermetic writes."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.tmp_dir = Path(self._tmp.name)
        self.cli_log = self.tmp_dir / "decisions.jsonl"

    def _run(self, *, record=None, raw=None, use_stdin=False):
        env = {
            **os.environ,
            "MIRU_DECISIONS_LOG_PATH": str(self.cli_log),
        }
        payload = json.dumps(record) if record is not None else (raw or "")

        if use_stdin:
            return subprocess.run(
                [sys.executable, str(EMIT_DECISION_PATH)],
                input=payload,
                text=True,
                capture_output=True,
                env=env,
                cwd=str(REPO_ROOT),
            )
        else:
            input_file = self.tmp_dir / "input.json"
            input_file.write_text(payload, encoding="utf-8")
            return subprocess.run(
                [sys.executable, str(EMIT_DECISION_PATH), "--input", str(input_file)],
                text=True,
                capture_output=True,
                env=env,
                cwd=str(REPO_ROOT),
            )

    def test_input_flag_works(self):
        result = self._run(record=_valid_judgment_record(), use_stdin=False)
        self.assertEqual(result.returncode, 0, msg=f"stderr={result.stderr}")
        self.assertIn("[emit_decision] written to", result.stderr)
        # decision_id printed on stdout (uuid4().hex = 32 chars)
        self.assertEqual(len(result.stdout.strip()), 32)
        self.assertTrue(self.cli_log.exists())
        lines = self.cli_log.read_text(encoding="utf-8").splitlines()
        self.assertEqual(len(lines), 1)

    def test_stdin_works(self):
        result = self._run(record=_valid_judgment_record(), use_stdin=True)
        self.assertEqual(result.returncode, 0, msg=f"stderr={result.stderr}")
        self.assertEqual(len(result.stdout.strip()), 32)

    def test_json_parse_failure_returns_clear_error(self):
        result = self._run(raw="this is not json", use_stdin=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn("[decision-validation]", result.stderr)
        self.assertIn("invalid JSON", result.stderr)

    def test_validation_error_human_readable(self):
        record = _valid_judgment_record(confidence="high", would_change_mind_if="")
        result = self._run(record=record, use_stdin=True)
        self.assertEqual(result.returncode, 1)
        lines = [ln for ln in result.stderr.splitlines() if ln.startswith("[decision-validation]")]
        self.assertGreater(len(lines), 0)

    def test_empty_stdin_returns_clear_error(self):
        result = self._run(raw="", use_stdin=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn("[decision-validation]", result.stderr)


