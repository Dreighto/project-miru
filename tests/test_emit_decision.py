class _DecisionTestBase(unittest.TestCase):
    """Each test gets its own temp log path and isolated MIRU_TRACE_ID."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.log_path = Path(self._tmp.name) / "decisions.jsonl"
        # Default: clear MIRU_TRACE_ID so identity auto-fill behavior is
        # explicit per-test. Tests that need it set use _env().
        self._saved_trace = os.environ.pop("MIRU_TRACE_ID", None)
        self.addCleanup(self._restore_trace)

    def _restore_trace(self):
        if self._saved_trace is not None:
            os.environ["MIRU_TRACE_ID"] = self._saved_trace

    def _emit(self, record):
        return emit_decision.emit(record, log_path=self.log_path)

    def _read_lines(self):
        if not self.log_path.exists():
            return []
        return [
            json.loads(ln)
            for ln in self.log_path.read_text(encoding="utf-8").splitlines()
            if ln.strip()
        ]


